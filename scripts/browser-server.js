import { mkdtempSync,rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { openStore } from '../src/store.js';
import { createApp } from '../src/app.js';
import { browserToken } from '../e2e/fixture.js';
const directory=mkdtempSync(join(tmpdir(),'matchmaking-browser-'));
const store=openStore(join(directory,'app.sqlite')),server=createApp(store,browserToken);
server.listen(Number(process.env.BROWSER_TEST_PORT||4187),'127.0.0.1');
for(const signal of ['SIGINT','SIGTERM'])process.once(signal,()=>server.close(()=>store.close()));
process.once('exit',()=>rmSync(directory,{recursive:true,force:true}));
